const NOW = Date.parse("2026-11-19T06:00:00Z");
const text = (markup: string): string => markup.replace(/<[^>]+>/g, " ").replace(/&#39;|&#x27;/g, "'").replace(/\s+/g, " ");
const titleOf = (page: string): string => /<title>([^<]*)<\/title>/.exec(page)![1]!.replace(/&#39;|&#x27;/g, "'");

let world: DemoWorld;
let launch: LaunchState & { launched: true };
let session: TrySession;
beforeAll(async () => {
  world = await buildDemoWorld();
  const l = loadLaunchState(world.bundleDir, world.publicKey);
  if (!l.launched) throw new Error("demo world did not launch");
  launch = l;
  const s = sessionLoader(world.bundleDir)();
  if (!s.ok) throw new Error("demo session did not load");
  session = s.session;
}, 120_000);
afterAll(() => rmSync(world.dir, { recursive: true, force: true }));

describe("finding 1: page titles never repeat the shop name", () => {
  it("home title is the shop name and a short tagline, once", () => {
    const t = titleOf(storefrontPage(launch, NOW));
    expect(t).toBe(homeTitle(launch.policy.business.name));
    expect(t.endsWith("Order online")).toBe(true);
    expect(t.split(launch.policy.business.name)).toHaveLength(2);
  });
  it("other pages append the shop name once; a title that holds it is left alone", () => {
    expect(pageTitle("Contact", "Meera's Kitchen")).toBe("Contact · Meera's Kitchen");
    expect(pageTitle("Meera's Kitchen", "Meera's Kitchen")).toBe("Meera's Kitchen");
    expect(pageTitle("Menu", null)).toBe("Menu");
  });
});

describe("finding 2: the owner's address is shown, escaped, and only when present", () => {
  it("contact page and footer carry a mailto link", () => {
    const page = contactPage(null, launch, "owner@example.test");
    expect(page.match(/href="mailto:owner@example\.test"/g)).toHaveLength(2);
    const footer = layout({ title: "T", body: html`<h1>x</h1>`, contactEmail: "owner@example.test" });
    expect(footer).toContain('Contact the owner</a> · <a href="mailto:owner@example.test">');
  });
  it("shows nothing when absent and never emits an unescaped or odd value", () => {
    expect(contactPage(null, launch, "")).not.toContain("mailto:");
    expect(layout({ title: "T", body: html``, contactEmail: "" })).not.toContain("mailto:");
    const evil = layout({ title: "T", body: html``, contactEmail: 'a"><script>x</script>@b.test' });
    expect(evil).not.toContain("<script>");
    expect(evil).not.toContain("mailto:");
  });
});

