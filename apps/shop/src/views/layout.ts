import { html, icon, raw, type SafeHtml } from "@agentdoor/ui";

export type NavKey = "menu" | "order" | "contact" | "report";

export interface ShopIdentity {
  name: string;
  /** One plain line for the footer, e.g. "Closed on Mondays". */
  hours?: string;
}

export interface LayoutOptions {
  title: string;
  body: SafeHtml;
  /** The shop-isn't-open banner (chili, top of page). */
  banner?: string;
  shop?: ShopIdentity;
  active?: NavKey;
  /** `try` swaps the shop header for the sticky replay navigation (S8). */
  chrome?: "shop" | "try";
  tryNav?: SafeHtml;
  description?: string;
  /** Script files under /assets (never inline: strict CSP). */
  scripts?: string[];
  /** frame-src is only opened on /try, so only the replay may embed the demo video. */
  bodyClass?: string;
}

const DEFAULT_SHOP: ShopIdentity = { name: "The shop" };
const NAV: { key: NavKey; href: string; label: string }[] = [
  { key: "menu", href: "/", label: "Menu" },
  { key: "order", href: "/order", label: "Order" },
  { key: "contact", href: "/contact", label: "Contact" },
  { key: "report", href: "/launch-report", label: "Launch report" },
];

/** Shown on every page (06 §3): the shop is generated, and the visitor can try the launcher. */
const ribbon = html`<aside class="ribbon" aria-label="About this site">
  <p class="ribbon__text">${icon("door")}<strong>Generated by AgentDoor</strong></p>
  <ul class="ribbon__links">
    <li><a href="/try">Try the launcher <span aria-hidden="true">→</span></a></li>
    <li><a href="/launch-report">Launch report</a></li>
    <li><a href="/try#demo">Demo video</a></li>
  </ul>
</aside>`;

function siteHeader(shop: ShopIdentity, active: NavKey | undefined): SafeHtml {
  return html`<header class="site-head">
    <div class="wrap site-head__row">
      <a class="brand" href="/"><span class="brand__mark">${icon("door")}</span><span class="brand__name">${shop.name}</span></a>
      <nav class="site-nav" aria-label="Main">
        <ul>
          ${NAV.map((n) => html`<li><a href="${n.href}" ${n.key === active ? raw('aria-current="page"') : ""}>${n.label}</a></li>`)}
        </ul>
      </nav>
    </div>
  </header>`;
}

function footer(shop: ShopIdentity): SafeHtml {
  return html`<footer class="site-foot">
    <div class="wrap site-foot__grid">
      <div>
        <p class="site-foot__name">${shop.name}</p>
        ${shop.hours ? html`<p>${shop.hours}</p>` : ""}
        <p><a href="/contact">Contact the owner</a></p>
      </div>
      <div>
        <p>Prices are set by the owner. Quotes are signed, so nobody can change them afterwards.</p>
        <p><a href="/launch-report">How this shop was checked</a> · <a href="/try">Try AgentDoor</a></p>
      </div>
    </div>
  </footer>`;
}

/** The page shell: no inline script or style anywhere, so the strict CSP holds. */
export function layout(o: LayoutOptions): string {
  const shop = o.shop ?? DEFAULT_SHOP;
  const tryMode = o.chrome === "try";
  return html`<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${o.title}${shop === DEFAULT_SHOP ? "" : ` · ${shop.name}`}</title>
<meta name="description" content="${o.description ?? `${shop.name}: order home-baked goods with prices and rules set by the owner.`}">
<meta name="color-scheme" content="light">
<link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="/assets/tokens.css">
<link rel="stylesheet" href="/assets/ui.css">
<link rel="stylesheet" href="/assets/shop.css">
</head>
<body class="${o.bodyClass ?? ""}">
<a class="skip" href="#main">Skip to the content</a>
${ribbon}
${o.banner ? html`<p class="banner-closed" role="alert">${icon("alert")}<strong>${o.banner}</strong></p>` : ""}
${tryMode ? (o.tryNav ?? "") : siteHeader(shop, o.active)}
<main id="main" tabindex="-1">
${o.body}
</main>
${tryMode ? "" : footer(shop)}
${(o.scripts ?? []).map((s) => html`<script src="/assets/${s}" defer></script>`)}
</body>
</html>`.value;
}
