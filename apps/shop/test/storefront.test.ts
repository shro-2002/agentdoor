import { buildDemoWorld, type DemoWorld } from "../../../e2e/support/demo-world.js";

const NOW = Date.parse("2026-11-19T06:00:00Z");
const FORBIDDEN_ON_BAKERY = ["Replay the launch", "Launch report", "Demo video", "Generated by AgentDoor"];

type Item = BusinessPolicy["catalog"][number];

const product = (id: string, name: string, unit: Item["unit"], unitPricePaise: number, dietary: Item["dietary"], prepHours: number, maxQtyPerOrder: number): Item => ({
  id,
  name: { en: name },
  unit,
  unitPricePaise,
  dietary,
  prepHours,
  minQty: 1,
  maxQtyPerOrder,
  capacityUnitsPerQty: 1,
  options: [],
});

/** The four real products by catalog id, with prices that differ from any default so a hardcoded price cannot pass. */
const PRODUCTS: Item[] = [
  product("chocolate-cake", "Chocolate cake", "kg", 61250, [], 48, 3),
  product("eggless-vanilla-cake", "Eggless vanilla cake", "kg", 66000, ["eggless"], 48, 3),
  product("cookie-box", "Cookie box", "box", 35500, [], 24, 10),
  product("brownies", "Brownies", "dozen", 48500, [], 24, 5),
];

let world: DemoWorld;
let launch: LaunchState & { launched: true };
let session: TrySession;
let shop: LaunchState & { launched: true };

beforeAll(async () => {
  world = await buildDemoWorld();
  const l = loadLaunchState(world.bundleDir, world.publicKey);
  if (!l.launched) throw new Error("demo world did not launch");
  launch = l;
  shop = { ...l, policy: { ...l.policy, catalog: PRODUCTS } };
  const s = sessionLoader(world.bundleDir)();
  if (!s.ok) throw new Error("demo session did not load");
  session = s.session;
}, 120_000);
afterAll(() => rmSync(world.dir, { recursive: true, force: true }));

describe("bakery storefront (/)", () => {
  it("shows all four products with the policy's own price, unit, link and photo alt text", () => {
    const page = storefrontPage(shop);
    for (const p of PRODUCTS) {
      expect(page, p.id).toContain(`/order?item=${p.id}`);
      expect(page, p.id).toContain(inr(p.unitPricePaise));
      expect(page, p.id).toContain(`alt="${PRODUCT_PHOTOS[p.id]!.alt}"`);
      expect(page, p.id).toContain(`/assets/photos/${PRODUCT_PHOTOS[p.id]!.file}`);
    }
    expect(page).toContain("₹612.50");
    expect(page).toContain("per kg");
    expect(page).toContain("per dozen");
    // The eggless cue comes from the policy's dietary tag, on that product only.
    expect(page.match(/>Eggless</g)).toHaveLength(1);
  });

  it("every image has size, alt text and the right loading hint: the hero is eager and high priority, the rest lazy", () => {
    const imgs = storefrontPage(shop).match(/<img [^>]*>/g)!;
    expect(imgs).toHaveLength(10);
    for (const img of imgs) {
      expect(img).toMatch(/ width="\d+"/);
      expect(img).toMatch(/ height="\d+"/);
      expect(img).toMatch(/ alt="[^"]{20,}"/);
    }
    expect(imgs.filter((i) => i.includes('fetchpriority="high"'))).toHaveLength(1);
    expect(imgs.filter((i) => i.includes('loading="lazy"'))).toHaveLength(9);
    expect(imgs[0]).toContain("hero-chocolate-cake.jpg");
    expect(imgs[0]).not.toContain("lazy");
  });

  it("has the ten sections in order, with a single h1", () => {
    const page = storefrontPage(shop);
    const at = (needle: string): number => {
      const i = page.indexOf(needle);
      expect(i, needle).toBeGreaterThan(-1);
      return i;
    };
    const order = ['class="hero"', 'id="menu"', 'class="kitchen"', 'id="occasions"', 'class="custom"', 'id="how"', 'id="delivery"', 'class="faq"', 'class="foot"'].map(at);
    expect(order).toEqual([...order].sort((a, b) => a - b));
    expect(page.match(/<h1[ >]/g)).toHaveLength(1);
    expect(page).toContain("Fresh from the oven");
    expect(page).toContain('href="/contact">Ask about a custom cake');
    expect(page.match(/<details class="faq__item">/g)!.length).toBeGreaterThanOrEqual(4);
  });

  it("header nav is Cakes and bakes, Occasions, How to order, Contact and an Order button; no platform links anywhere", () => {
    const page = storefrontPage(shop);
    const header = /<header class="head">[\s\S]*?<\/header>/.exec(page)![0];
    for (const link of ['href="/#menu">Cakes and bakes', 'href="/#occasions">Occasions', 'href="/#how">How to order', 'href="/contact">Contact', 'class="btn btn--primary head__order" href="/order">Order']) {
      expect(header, link).toContain(link);
    }
    for (const old of FORBIDDEN_ON_BAKERY) expect(page, old).not.toContain(old);
    expect(page).not.toContain("Source code");
  });

  it("footer credits Pexels, links Powered by AgentDoor to /launch and keeps the persona note and contact link", () => {
    const footer = /<footer class="foot">[\s\S]*<\/footer>/.exec(storefrontPage(shop))![0];
    expect(footer).toContain('Photos: <a href="https://www.pexels.com" rel="noopener">Pexels</a>');
    expect(footer).toContain('Powered by <a href="/launch">AgentDoor</a>');
    expect(footer).toContain("Illustrative persona based on common home-bakery practices.");
    expect(footer).toContain('href="/contact"');
  });

  it("delivery and pickup facts are generated from the policy", () => {
    const { fulfilment, rush } = launch.policy;
    const page = storefrontPage(launch);
    for (const a of fulfilment.delivery.areas) expect(page).toContain(`<strong>${a.name}</strong><span>${areaFee(a.feePaise)}</span>`);
    if (rush) expect(page).toContain(`<strong>${rushFee(rush)}</strong>`);
  });
});

describe("order page (/order)", () => {
  const page = (): string => orderPage({ launch: shop, values: emptyValues(), earliest: earliestDate(shop.policy, NOW), nowMs: NOW });

  it("shows photo cards, a real number input per product and both fulfilment cards", () => {
    const html = page();
    for (const p of PRODUCTS) {
      expect(html).toContain(`name="qty.${p.id}"`);
      expect(html).toContain(`alt="${PRODUCT_PHOTOS[p.id]!.alt}"`);
    }
    expect(html.match(/<div class="qty" data-qty>/g)).toHaveLength(4);
    expect(html).toContain('type="number"');
    expect(html).toMatch(/<input type="radio" name="fulfilment" value="pickup"/);
    expect(html).toMatch(/<input type="radio" name="fulfilment" value="delivery"/);
    expect(html).toContain("Your order");
    expect(html).toContain('<script src="/assets/shop.js" defer></script>');
    expect(html).not.toMatch(/\sstyle=/);
  });

  it("the date picker's earliest day is the engine's own, and the summary never shows a price", () => {
    const min = earliestDate(shop.policy, NOW);
    expect(min).not.toBeNull();
    expect(page()).toContain(`min="${min}"`);
    const summary = /<aside class="summary"[\s\S]*?<\/aside>/.exec(page())![0];
    expect(summary).not.toContain("₹");
  });

  it("the quote page prices from the quote result only: lines, rush, delivery and total, nothing else", () => {
    const line = { itemId: "chocolate-cake", qty: 2, optionIds: [], unitPricePaise: 61250, optionsPaise: 0, lineTotalPaise: 122500 };
    const quote = { token: "t", expiresAtMs: NOW + 60_000, totalPaise: 122500 + 20000 + 8000, lines: [line], isRush: true, rushPaise: 20000, deliveryPaise: 8000 };
    const html = quotePage({
      launch: shop,
      values: emptyValues(),
      quote,
      request: { lines: [{ itemId: "chocolate-cake", qty: 2, optionIds: [] }], fulfilment: { kind: "delivery", area: "Aundh" }, date: "2026-11-21" },
      idempotencyKey: "k",
      customer: { name: "", phone: "", address: "" },
      changeHref: "/order",
    });
    for (const amount of ["₹1225", "₹200", "₹80", "₹1505"]) expect(html).toContain(amount);
    expect(html).toContain("Rush order");
    expect(html).not.toMatch(/discount/i);
  });
});

describe("AgentDoor landing (/launch)", () => {
  it("leads with the exact headline and the first-run critical-gap number taken from the recorded session", () => {
    const story = buildLaunchStory(session, launch.record, NOW);
    const expected = liveRunFigures("First rehearsal run", runLive(session, 1, NOW)).gaps.critical;
    expect(story.first.gaps.critical).toBe(expected);
    const page = launchPage(story);
    expect(page).toContain(`<h1 id="launch-h" class="ad-hero__title">${esc(LAUNCH_HEADLINE)}</h1>`);
    expect(LAUNCH_HEADLINE).toBe("Don't just launch your business. Rehearse it before your first customer arrives.");
    expect(page).toContain(`<strong class="figure__n">${expected}</strong>`);
    expect(page).toContain(`<strong class="figure__n">${story.final.gaps.open}</strong>`);
    for (const name of ["Describe", "Clarify", "Review business rules", "Rehearse", "Resolve", "Launch"]) expect(page).toContain(`<h3>${name}</h3>`);
  });

  it("is honest: a recorded real launch, the live launcher is coming next, and the CTAs go where they say", () => {
    const page = launchPage(buildLaunchStory(session, launch.record, NOW));
    expect(page).toContain("recorded real launch, made with live Claude");
    expect(page).toContain("The interactive live launcher is coming next.");
    expect(page).toContain('href="/try">Walk through the real launch session');
    expect(page).toContain('href="/launch-report">See the launch report');
    expect(page).toContain('rel="noopener">Source code</a>');
    expect(page).not.toContain("/assets/bakery.css");
    expect(page).not.toMatch(/\sstyle=/);
  });

  it("every gap card and correction is real session data, in plain words", () => {
    const story = buildLaunchStory(session, launch.record, NOW);
    expect(story.corrections).toHaveLength(session.gapFixes.length);
    const page = launchPage(story);
    for (const g of story.gaps) expect(page).toContain(esc(g.title));
    for (const c of story.corrections) expect(page).toContain(esc(c.decision));
  });

  it("still renders the headline and links when the recorded session is missing, and says so", () => {
    const page = launchPage(null);
    expect(page).toContain(esc(LAUNCH_HEADLINE));
    expect(page).toContain("not available on this server");
    expect(page).toContain('href="/try"');
  });
});

describe("routes", () => {
  let server: Server;
  let base = "";
  beforeAll(async () => {
    process.env.BUNDLE_DIR = world.bundleDir;
    const config: ShopConfig = {
      port: 0,
      nodeEnv: "test",
      db: { host: "x", port: 1, database: "x", user: "x", password: "x" },
      signingPrivateKey: world.privateKey,
      signingPublicKey: world.publicKey,
      sessionSecret: Buffer.alloc(32, 5),
      ownerTokenHash: createHash("sha256").update("t").digest("hex"),
      contactRecipient: "owner@example.test",
      publicBaseUrl: "https://shop.test",
      platformBaseUrl: null,
    };
    server = createServer(createApp({ config, pool: {} as Pool, launch, now: () => NOW, log: () => undefined }));
    await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
    base = "http://127.0.0.1:" + (server.address() as AddressInfo).port;
  });
  afterAll(() => new Promise<void>((r) => server.close(() => r())));

  it("GET /launch serves the AgentDoor page under the strict CSP, with no frame and no inline code", async () => {
    const res = await fetch(`${base}/launch`);
    expect(res.status).toBe(200);
    const csp = res.headers.get("content-security-policy")!;
    expect(csp).not.toContain("unsafe-inline");
    expect(csp).not.toContain("frame-src");
    const body = await res.text();
    expect(body).toContain(esc(LAUNCH_HEADLINE));
    expect(body).not.toMatch(/<script(?![^>]*src=)/);
  });

  it("GET / is the bakery, and the bakery and AgentDoor stylesheets are served", async () => {
    const home = await (await fetch(`${base}/`)).text();
    expect(home).toContain("/assets/bakery.css");
    for (const f of ["bakery.css", "agentdoor.css", "agentdoor-launch.css", "agentdoor-try.css", "photos/hero-chocolate-cake.jpg"]) {
      const res = await fetch(`${base}/assets/${f}`);
      expect(res.status, f).toBe(200);
    }
  });
});
