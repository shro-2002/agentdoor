import { html, icon, type SafeHtml } from "@agentdoor/ui";
import { personaNote } from "../persona.js";
import { MAILBOX, contactLink, type ShopIdentity } from "./shared.js";

/**
 * The private owner pages keep the original shop chrome (ribbon, ledger header and footer), so the
 * dashboard looks the same as before the storefront was redesigned.
 */
const NAV = [
  { href: "/", label: "Menu" },
  { href: "/order", label: "Order" },
  { href: "/contact", label: "Contact" },
  { href: "/launch-report", label: "Launch report" },
];

export const ownerRibbon = html`<aside class="ribbon" aria-label="About this site">
  <p class="ribbon__text">${icon("door")}<strong>Generated by AgentDoor</strong></p>
  <ul class="ribbon__links">
    <li><a href="/try">Replay the launch <span aria-hidden="true">→</span></a></li>
    <li><a href="/launch-report">Launch report</a></li>
    <li><a href="/try#demo">Demo video</a></li>
  </ul>
</aside>`;

export function ownerHeader(shop: ShopIdentity): SafeHtml {
  return html`<header class="site-head">
    <div class="wrap site-head__row">
      <a class="brand" href="/"><span class="brand__mark">${icon("door")}</span><span class="brand__name">${shop.name}</span></a>
      <nav class="site-nav" aria-label="Main">
        <ul>${NAV.map((n) => html`<li><a href="${n.href}">${n.label}</a></li>`)}</ul>
      </nav>
    </div>
  </header>`;
}

export function ownerFooter(shop: ShopIdentity, email: string, repoUrl: string): SafeHtml {
  return html`<footer class="site-foot">
    <div class="wrap site-foot__grid">
      <div>
        <p class="site-foot__name">${shop.name}</p>
        ${shop.hours ? html`<p>${shop.hours}</p>` : ""}
        <p><a href="/contact">Contact the owner</a>${MAILBOX.test(email) ? html` · ${contactLink(email)}` : ""}</p>
      </div>
      <div>
        <p>Prices are set by the owner. Quotes are signed, so nobody can change them afterwards.</p>
        <p><a href="/launch-report">How this shop was checked</a> · <a href="/try">Replay the launch</a>${repoUrl ? html` · <a href="${repoUrl}" rel="noopener">Source code</a>` : ""}</p>
      </div>
      <div class="site-foot__note">${personaNote()}</div>
    </div>
  </footer>`;
}
