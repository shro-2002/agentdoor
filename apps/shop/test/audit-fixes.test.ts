describe("finding 4: friendly 404 and robots.txt", () => {
  let server: Server;
  let base = "";
  beforeAll(async () => {
    const config: ShopConfig = {
      port: 0,
      nodeEnv: "test",
      db: { host: "x", port: 1, database: "x", user: "x", password: "x" },
      signingPrivateKey: world.privateKey,
      signingPublicKey: world.publicKey,
      sessionSecret: Buffer.alloc(32, 5),
      ownerTokenHash: createHash("sha256").update("t").digest("hex"),
      contactRecipient: "owner@example.test",
      publicBaseUrl: "https://shop.test",
      platformBaseUrl: null,
    };
    const app = createApp({ config, pool: {} as Pool, launch, now: () => NOW, log: () => undefined });
    server = createServer(app);
    await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
    base = "http://127.0.0.1:" + (server.address() as AddressInfo).port;
  });
  afterAll(() => new Promise<void>((r) => server.close(() => r())));

  const get = (path: string, accept: string) => fetch(base + path, { headers: { accept } });

  it("browsers get a 404 page in the shop layout, with no reflected input", async () => {
    const res = await get("/nope%3Cscript%3Ealert(1)%3C/script%3E?q=%3Cb%3E", "text/html,application/xhtml+xml");
    expect(res.status).toBe(404);
    expect(res.headers.get("content-type")).toContain("text/html");
    const body = await res.text();
    expect(body).toContain("Generated by AgentDoor");
    expect(body).toContain('aria-label="Main"');
    expect(body).toContain("Replay the launch");
    expect(body).toContain('href="mailto:owner@example.test"');
    expect(body).not.toContain("alert(1)");
    expect(body).not.toContain("nope");
  });
  it("API-style paths keep the JSON envelope even for a browser Accept", async () => {
    for (const p of ["/api/nothing", "/.well-known/nothing", "/.well-known/oauth-authorization-server"]) {
      const res = await get(p, "text/html");
      expect(res.status).toBe(404);
      expect(res.headers.get("content-type")).toContain("application/json");
      expect((await res.json()).error.code).toBe("NOT_FOUND");
    }
    const plain = await get("/whatever", "application/json");
    expect(plain.status).toBe(404);
    expect((await plain.json()).error.code).toBe("NOT_FOUND");
  });
  it("serves a small text/plain robots.txt", async () => {
    const res = await get("/robots.txt", "*/*");
    expect(res.status).toBe(200);
    expect(res.headers.get("content-type")).toContain("text/plain");
    expect(await res.text()).toBe(ROBOTS_TXT);
    expect(ROBOTS_TXT).toBe("User-agent: *\nAllow: /\n");
  });
  it("security headers are identical on the 404 page, the JSON 404 and robots.txt", async () => {
    const a = await get("/nope", "text/html");
    const b = await get("/api/nope", "application/json");
    const c = await get("/robots.txt", "*/*");
    const names = [...b.headers.keys()].filter((n) => !["content-type", "content-length", "etag", "date", "x-request-id", "connection", "keep-alive"].includes(n));
    expect(names).toContain("content-security-policy");
    for (const n of names) {
      expect(a.headers.get(n)).toBe(b.headers.get(n));
      expect(c.headers.get(n)).toBe(b.headers.get(n));
    }
  });
});

describe("finding 7: shared helpers", () => {
  it("gapFigures counts found, critical, fixed, open from the same rows", () => {
    const rows = [
      { severity: "critical" as const, fixedInVersion: 2 },
      { severity: "critical" as const, fixedInVersion: null },
      { severity: "warning" as const, fixedInVersion: 3 },
    ];
    expect(gapFigures(rows)).toEqual({ found: 3, critical: 2, fixed: 2, open: 1 });
    expect(gapFigures([])).toEqual({ found: 0, critical: 0, fixed: 0, open: 0 });
  });

  it("ownerQuoteFor takes the transcript quote, else the recorded evidence quote, never an invented one", () => {
    const base = Object.values(launch.policy.provenance)[0]!;
    const transcript = { ...base, source: { kind: "transcript" as const, quote: "I said so", turn: 0 } };
    const edited = { ...base, source: { kind: "owner_edit" as const, note: "Edited by owner" } };
    const ev = [
      { path: "p", quote: "original words" },
      { path: "q", quote: null },
      { path: "r", quote: "  " },
    ];
    expect(ownerQuoteFor("p", transcript, ev)).toBe("I said so");
    expect(ownerQuoteFor("p", edited, ev)).toBe("original words");
    expect(ownerQuoteFor("q", edited, ev)).toBeNull();
    expect(ownerQuoteFor("r", edited, ev)).toBeNull();
    expect(ownerQuoteFor("zzz", edited, ev)).toBeNull();
  });

  it("approvalFigures reports approved of required and lists the total separately", () => {
    const a = approvalFigures(launch.policy);
    expect(a.required).toBe(launch.record.approvals.required);
    expect(a.approvedRequired).toBe(launch.record.approvals.approved);
    expect(a.listed).toBe(Object.keys(launch.policy.provenance).length);
    expect(a.approvedRequired).toBeLessThanOrEqual(a.required);
  });
});

describe("finding 7: both pages agree, on the real exported session shape", () => {
  const evidence = () => session.compile.result.evidence;

  it("rules with owner-quote evidence: /try/rules and /launch-report use one count", () => {
    const first = session.policyVersions[0]!;
    const n = quoteEvidenceFigures(first, evidence());
    expect(text(rulesPage(session))).toContain(n.withQuote + " point back to a sentence the owner said");
    const nFinal = quoteEvidenceFigures(launch.policy, evidence());
    const report = text(launchReportPage(launch, "https://x.test", { evidence: evidence() }));
    expect(report).toContain(nFinal.withQuote + " of the " + nFinal.total + " point back");
    // Same rules, two versions: the first draft is labelled as such, the report counts the final rules.
    expect(text(rulesPage(session))).toContain("In the first draft, " + n.withQuote + " point back");
    expect(nFinal.total).toBe(n.total);
  });

  it("a rule with a quote never carries the AgentDoor-suggested label; one with a default source and no quote does", () => {
    for (const e of ruleEntries(launch.policy, evidence())) {
      if (e.quote !== null) expect(e.note ?? "").not.toBe(SUGGESTED_NOTE);
      if (e.note === SUGGESTED_NOTE) expect(e.quote).toBeNull();
    }
    const without = ruleEntries(launch.policy);
    const withEv = ruleEntries(launch.policy, evidence());
    for (const r of withEv.filter((e) => e.quote !== null && without.find((w) => w.path === e.path)!.quote === null)) {
      expect(evidence().some((x) => x.quote === r.quote)).toBe(true);
    }
  });

  it("rules approved are shown as approved of required, with the listed total explained", () => {
    const a = approvalFigures(launch.policy);
    const report = text(launchReportPage(launch, "https://x.test", { evidence: evidence() }));
    expect(report).toContain("required rules approved");
    expect(report).toContain(a.approvedRequired + "/" + a.required);
    expect(report).toContain(a.listed + " rules are listed");
  });

  it("first-run and final-run numbers carry explicit labels and are identical on both pages", () => {
    const first = liveRunFigures("First rehearsal run", runLive(session, 1, NOW));
    const final = recordedRunFigures(launch.record);
    expect(final.label).toBe("Final rehearsal run");
    expect(final.checks).toBe(launch.record.rehearsal.probes + launch.record.rehearsal.scenarios);
    expect(final.passed).toBe(launch.record.rehearsal.passed);
    expect(final.gaps.found).toBe(launch.record.rehearsal.gapsFound.length);

    const report = launchReportPage(launch, "https://x.test", { evidence: evidence(), firstRun: first });
    const last = session.policyVersions.length;
    const rehearse = rehearsePage({
      session,
      run: runLive(session, firstProblemVersion(session, NOW), NOW),
      latest: runLive(session, last, NOW),
      tabs: [],
      earliest: null,
      quotePolicy: launch.policy,
      runs: [first, final],
    });
    const cells = (page: string, label: string): string[] => {
      const row = new RegExp('<th scope="row">' + label + "</th>(.*?)</tr>").exec(page)![1]!;
      return [...row.matchAll(/<td class="num">(\d+)<\/td>/g)].map((m) => m[1]!);
    };
    for (const label of ["First rehearsal run", "Final rehearsal run"]) expect(cells(report, label)).toEqual(cells(rehearse, label));
    expect(cells(report, "Final rehearsal run")).toEqual([String(final.checks), String(final.passed), String(final.gaps.open)]);
    expect(cells(report, "First rehearsal run")).toEqual([String(first.checks), String(first.passed), String(first.gaps.open)]);
  });
});
