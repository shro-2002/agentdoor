import { expect, test } from "@playwright/test";
import { watchConsole } from "./helpers.js";
import { SHOP, ownerLogin, placeOrderViaPages, tableCounts } from "./shop-helpers.js";

const RIBBON = "Generated by AgentDoor";

test.describe("E2E-2 human order flow: menu -> quote -> request order -> status page", () => {
  test("with JavaScript", async ({ page }) => {
    const problems = watchConsole(page);
    await page.goto(`${SHOP()}/`);
    await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
    await expect(page.locator(".ribbon")).toContainText(RIBBON);
    await expect(page.locator(".ribbon").getByRole("link", { name: /Try the launcher/ })).toHaveAttribute("href", "/try");
    await expect(page.locator(".dish").first()).toContainText("₹");
    const before = (await tableCounts()).orders;
    const url = await placeOrderViaPages(page);
    await expect(page.getByRole("heading", { level: 1 })).toContainText("Waiting for");
    await expect(page.locator(".ribbon")).toContainText(RIBBON);
    await expect(page.getByLabel("Private link to this order")).toHaveValue(/\/orders\/.+\?t=/);
    expect((await tableCounts()).orders).toBe(before + 1);
    // The private link keeps working; a wrong token is a plain not-found, not an oracle.
    await page.goto(url);
    await expect(page.getByText("Waiting for")).toBeVisible();
    expect(problems).toEqual([]);
    const wrong = await page.goto(url.replace(/t=.{6}/, "t=AAAAAA"));
    expect(wrong?.status()).toBe(404);
  });

  test.describe("without JavaScript", () => {
    test.use({ javaScriptEnabled: false });
    test("the same flow with plain form posts", async ({ page }) => {
      const url = await placeOrderViaPages(page, "No Script");
      await expect(page.getByRole("heading", { level: 1 })).toContainText("Waiting for");
      expect(url).toContain("/orders/");
    });
  });

  test("a refused quote says why, in plain words, and keeps the form", async ({ page }) => {
    await page.goto(`${SHOP()}/order`);
    const qty = page.locator("input.qty__input").first();
    await qty.fill("1");
    const today = await page.locator("#date").getAttribute("min");
    await page.locator("#date").fill(today!);
    await page.getByRole("button", { name: "Get my quote" }).click();
    const alert = page.getByRole("alert").first();
    await expect(alert).toContainText("can't quote this yet");
    await expect(page.locator("#err-date")).toContainText(/notice|closed|earliest/i);
    await expect(page.locator("#date")).toHaveAttribute("aria-invalid", "true");
    await expect(qty).toHaveValue("1");
  });

  test("a tampered quote is refused, never priced again", async ({ page, request }) => {
    await page.goto(`${SHOP()}/order`);
    await page.locator("input.qty__input").first().fill("1");
    await page.getByRole("button", { name: "Get my quote" }).click();
    await expect(page.getByRole("heading", { level: 1, name: "Your quote" })).toBeVisible();
    await page.locator('input[name="quoteToken"]').evaluate((el: HTMLInputElement) => (el.value = `${el.value.slice(0, -4)}AAAA`));
    await page.getByLabel("Name").fill("Mallory");
    await page.getByLabel(/^Phone/).fill("9876543210");
    const before = (await tableCounts()).orders;
    await page.getByRole("button", { name: "Request order" }).click();
    await expect(page.getByRole("heading", { level: 1 })).toContainText(/not valid|Not found|request/i);
    expect((await tableCounts()).orders).toBe(before);
    expect((await request.get(`${SHOP()}/healthz`)).ok()).toBe(true);
  });
});

test.describe("E2E-4 owner login -> confirm an order -> status changes", () => {
  test("the owner confirms and the customer's page follows", async ({ page, browser }) => {
    const customer = await browser.newContext();
    const customerPage = await customer.newPage();
    const statusUrl = await placeOrderViaPages(customerPage, "Priya Confirm");

    const unauth = await page.goto(`${SHOP()}/owner`);
    expect(new URL(unauth!.url()).pathname).toBe("/owner/login");
    await page.getByLabel("Owner token").fill("not-the-token");
    await page.getByRole("button", { name: "Sign in" }).click();
    await expect(page.getByRole("alert")).toContainText("not valid");

    await ownerLogin(page);
    await expect(page.getByRole("link", { name: /^Pending/ })).toHaveAttribute("aria-current", "page");
    const row = page.locator("tr", { hasText: "Priya Confirm" });
    await expect(row).toBeVisible();
    await expect(row).toContainText("PENDING");
    await row.getByRole("button", { name: /^Confirm order / }).click();
    await expect(page.locator("tr", { hasText: "Priya Confirm" })).toHaveCount(0); // gone from Pending
    await page.getByRole("link", { name: /^Confirmed/ }).click();
    await expect(page.locator("tr", { hasText: "Priya Confirm" })).toContainText("CONFIRMED");

    await customerPage.goto(statusUrl);
    await expect(customerPage.getByRole("heading", { level: 1 })).toContainText("confirmed your order");
    await customer.close();

    await page.getByRole("button", { name: "Sign out" }).click();
    await expect(page).toHaveURL(/\/owner\/login$/);
    await page.goto(`${SHOP()}/owner`);
    expect(new URL(page.url()).pathname).toBe("/owner/login");
  });

  test("declining asks for confirmation first, with no script", async ({ browser }) => {
    const ctx = await browser.newContext({ javaScriptEnabled: false });
    const customerPage = await ctx.newPage();
    await placeOrderViaPages(customerPage, "Dev Decline");
    await ownerLogin(customerPage);
    const row = customerPage.locator("tr", { hasText: "Dev Decline" });
    await row.getByText("Decline", { exact: true }).click();
    await row.getByRole("button", { name: /^Yes, decline order /i }).click();
    await customerPage.getByRole("link", { name: /^All/ }).click();
    await expect(customerPage.locator("tr", { hasText: "Dev Decline" })).toContainText("DECLINED");
    await ctx.close();
  });
});

test.describe("S4 contact", () => {
  test("thank-you and the honeypot", async ({ page }) => {
    await page.goto(`${SHOP()}/contact`);
    await expect(page.getByRole("heading", { level: 1 })).toContainText("Contact");
    await page.getByLabel("Your name").fill("Rhea");
    await page.getByLabel(/^Your email/).fill("rhea@example.test");
    await page.getByLabel("Message").fill("Do you do vegan cakes?");
    const before = (await tableCounts()).contact_messages;
    await page.getByRole("button", { name: "Send message" }).click();
    await expect(page).toHaveURL(/sent=1/);
    await expect(page.getByRole("status")).toContainText("Thank you");
    expect((await tableCounts()).contact_messages).toBe(before + 1);
    await page.goto(`${SHOP()}/contact?sent=0`);
    await expect(page.getByRole("status")).toContainText("saved your message");
  });
});

test("S5 launch report shows the owner's words, the gaps and the fingerprint", async ({ page }) => {
  await page.goto(`${SHOP()}/launch-report`);
  await expect(page.getByRole("heading", { level: 1 })).toContainText("was prepared for launch");
  await expect(page.locator(".tiles")).toContainText("rules approved");
  await expect(page.locator(".rule__quote").first()).toContainText("You said:");
  await expect(page.getByRole("heading", { name: "What the rehearsal caught" })).toBeVisible();
  await expect(page.locator(".tg").first()).toBeVisible();
  const hash = await page.locator("dd.mono").first().innerText();
  expect(hash).toMatch(/^[0-9a-f]{64}$/);
  const live = await page.request.get(`${SHOP()}/healthz`);
  expect((await live.json()).data.policyHash).toBe(hash);
});
