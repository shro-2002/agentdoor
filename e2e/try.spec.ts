import { expect, test, type Page } from "@playwright/test";
import { watchConsole } from "./helpers.js";
import { SHOP, SHOP_NO_SESSION, tableCounts } from "./shop-helpers.js";

const BADGES = { claude: "RECORDED · Claude", live: "LIVE · deterministic", deploy: "RECORDED · deployment evidence" };

async function badgesOn(page: Page): Promise<string[]> {
  return page.locator(".prov__tag").allInnerTexts().then((t) => [...new Set(t.map((s) => s.trim()))]);
}

test.describe("E2E-5 the public replay works end to end with JavaScript disabled", () => {
  test.use({ javaScriptEnabled: false });

  test("intro, four steps, three badges, a live quote that writes nothing", async ({ page }) => {
    const problems = watchConsole(page);
    const before = await tableCounts();
    await page.goto(`${SHOP()}/try`);
    await expect(page.getByRole("heading", { level: 1 })).toContainText("shop that can't be talked into a bad deal");
    await expect(page.locator(".ribbon")).toContainText("Generated by AgentDoor");

    // The video id is unset here: a clear note, never a broken iframe.
    await expect(page.locator("#demo")).toContainText("demo video link is added at submission");
    await expect(page.locator("iframe")).toHaveCount(0);

    // The legend lists all three badges.
    expect(await badgesOn(page)).toEqual(expect.arrayContaining(Object.values(BADGES)));

    // Persistent navigation on every page.
    const nav = page.getByRole("navigation", { name: "Replay navigation" });
    for (const name of ["Storefront", "Launch report", "Watch demo"]) await expect(nav.getByRole("link", { name })).toBeVisible();

    const seen = new Set<string>();
    await page.getByRole("link", { name: /^Start the replay/ }).click();
    await expect(page).toHaveURL(/\/try\/describe$/);
    await expect(page.getByRole("heading", { level: 1 })).toContainText("describes the business");
    await expect(page.locator("blockquote.transcript")).not.toBeEmpty();
    for (const b of await badgesOn(page)) seen.add(b);
    await expect(page.getByRole("navigation", { name: "Replay navigation" }).getByRole("link", { name: "Describe" })).toHaveAttribute("aria-current", "step");

    await page.getByRole("link", { name: /^Next: the rules/ }).click();
    await expect(page).toHaveURL(/\/try\/rules$/);
    await expect(page.locator("article.rule").first()).toBeVisible();
    await expect(page.locator(".rule__quote").first()).toContainText("You said:");
    expect(await page.locator("article.rule button").count()).toBe(0); // read-only: no approve buttons on the public page
    for (const b of await badgesOn(page)) seen.add(b);

    await page.getByRole("link", { name: /^Next: the rehearsal/ }).click();
    await expect(page).toHaveURL(/\/try\/rehearse/);
    await expect(page.locator("#receipt")).toBeVisible();
    await expect(page.locator("article.gap").first()).toBeVisible();
    await expect(page.locator("article.gap form")).toHaveCount(0);
    for (const b of await badgesOn(page)) seen.add(b);

    // The mini-form: a quote from the live engine; the orders table and every other table stay as they were.
    await page.getByLabel("Quantity").fill("2");
    await page.getByRole("button", { name: "Ask the rule engine" }).click();
    const result = page.locator("#quote-result");
    await expect(result).toBeVisible();
    await expect(result).toContainText("no order was created");
    await expect(result).toContainText(/QUOTED|REFUSED|NEEDS OWNER/);
    expect(await tableCounts()).toEqual(before);
    // A second ask on a closed or too-soon day is refused in plain words, and still writes nothing.
    await page.locator("#t-date").fill(new Date().toISOString().slice(0, 10));
    await page.getByRole("button", { name: "Ask the rule engine" }).click();
    await expect(page.locator("#quote-result")).toContainText(/REFUSED|NEEDS OWNER/);
    expect(await tableCounts()).toEqual(before);

    await page.getByRole("link", { name: /^Next: launch/ }).click();
    await expect(page).toHaveURL(/\/try\/launch$/);
    await expect(page.locator(".door")).toBeVisible();
    await expect(page.locator(".timeline .step").first()).toBeVisible();
    await expect(page.locator(".hash-compare")).toContainText("/healthz");
    for (const b of await badgesOn(page)) seen.add(b);

    expect([...seen].sort()).toEqual(Object.values(BADGES).sort());
    expect(await tableCounts()).toEqual(before);
    expect(problems).toEqual([]);
  });

  test("the nav goes to the storefront and the launch report", async ({ page }) => {
    await page.goto(`${SHOP()}/try/rules`);
    await page.getByRole("navigation", { name: "Replay navigation" }).getByRole("link", { name: "Launch report" }).click();
    await expect(page).toHaveURL(/\/launch-report$/);
    await expect(page.locator(".ribbon")).toContainText("Generated by AgentDoor");
  });

  test("version tabs re-run the rehearsal on each recorded policy version", async ({ page }) => {
    await page.goto(`${SHOP()}/try/rehearse?v=1`);
    const tabs = page.getByRole("navigation", { name: "Policy version" }).getByRole("link");
    expect(await tabs.count()).toBeGreaterThan(1);
    await tabs.last().click();
    await expect(page.getByRole("link", { current: "page" }).last()).toBeVisible();
    await expect(page.locator(".door, #receipt").first()).toBeVisible();
  });
});

test("a missing session file shows Replay unavailable, with the links, never a 500", async ({ page }) => {
  for (const p of ["/try", "/try/describe", "/try/rehearse", "/try/launch"]) {
    const res = await page.goto(`${SHOP_NO_SESSION()}${p}`);
    expect(res?.status()).toBe(200);
    await expect(page.getByRole("heading", { level: 1 })).toHaveText("Replay unavailable");
    await expect(page.getByRole("link", { name: "Visit the storefront" })).toBeVisible();
    await expect(page.locator("#demo")).toBeVisible();
  }
});

test("the CSP opens frame-src for the demo video on /try only", async ({ request }) => {
  const csp = async (p: string): Promise<string> => (await request.get(`${SHOP()}${p}`)).headers()["content-security-policy"] ?? "";
  expect(await csp("/try")).toContain("frame-src https://www.youtube-nocookie.com");
  expect(await csp("/try/rules")).toContain("frame-src https://www.youtube-nocookie.com");
  expect(await csp("/")).not.toContain("frame-src");
  expect(await csp("/order")).not.toContain("frame-src");
  expect(await csp("/try")).not.toContain("'unsafe-inline'");
});
